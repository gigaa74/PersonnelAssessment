def questions_for(bank_version):
    return QUESTIONS_V2 if bank_version == "2.0.0-pilot" else QUESTIONS


def validate_bank():
    errors = []
    if len(QUESTIONS) != 30:
        errors.append(f"expected 30 cognitive questions, got {len(QUESTIONS)}")
    if len({question.id for question in QUESTIONS}) != len(QUESTIONS):
        errors.append("cognitive question identifiers must be unique")
    for question in QUESTIONS:
        if not 1 <= question.correct <= len(question.choices):
            errors.append(f"{question.id}: invalid correct answer")
    return tuple(errors)
