from dataclasses import dataclass
from enum import StrEnum


class CognitiveDomain(StrEnum):
    LOGICAL = "logical"
    NUMERICAL = "numerical"
    VERBAL = "verbal"
    SPATIAL = "spatial"


DOMAIN_LABELS = {
    CognitiveDomain.LOGICAL: "Логическое мышление",
    CognitiveDomain.NUMERICAL: "Числовое мышление",
    CognitiveDomain.VERBAL: "Вербальное мышление",
    CognitiveDomain.SPATIAL: "Пространственное мышление",
}


@dataclass(frozen=True, slots=True)
class CognitiveQuestion:
    id: str
    text: str
    domain: CognitiveDomain
    choices: tuple[str, ...]
    correct: int
    kind: str = "cognitive"


def _item(code, number, domain, text, choices, correct):
    return CognitiveQuestion(f"{code}{number:02}", text, domain, tuple(choices), correct)


